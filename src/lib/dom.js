// ---------------------------------------------------------------- output encoding
// Every dynamic value rendered into HTML goes through esc(). Attribute values are
// always double-quoted in templates, so encoding the five characters is sufficient.
export const esc = (value = '') => String(value ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

export const icon = (name, cls = '') => `<svg class="${esc(cls)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${iconPaths[name] || iconPaths.sparkle}</svg>`;

export const initials = (name = '') => String(name).trim().split(/\s+/).slice(0, 2).map(p => p[0] || '').join('').toUpperCase();
export const avatar = (name, size = 'sm') => `<span class="avatar ${size}" aria-hidden="true">${esc(initials(name) || '?')}</span>`;
export const fmtInt = n => Number(n || 0).toLocaleString();

// Only allow http(s) links into href attributes.
export const safeUrl = u => (/^https:\/\//i.test(String(u || '')) ? String(u) : '');

let toastTimer;
export function toast(message, kind = 'ok') {
  const root = document.getElementById('toast-root');
  root.innerHTML = `<div class="toast ${kind === 'error' ? 'error' : ''}" role="status">${icon(kind === 'error' ? 'info' : 'check')}<span>${esc(message)}</span></div>`;
  const el = root.firstElementChild;
  requestAnimationFrame(() => el.classList.add('show'));
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), 3200);
}

let lastFocus = null;
export function openModal(title, subtitle, body, { wide = false, onClose } = {}) {
  lastFocus = document.activeElement;
  const root = document.getElementById('overlay-root');
  root.innerHTML = `<div class="modal-backdrop" data-backdrop><section class="modal ${wide ? 'wide' : ''}" role="dialog" aria-modal="true" aria-labelledby="modal-title"><header class="modal-head"><div><h2 id="modal-title">${esc(title)}</h2>${subtitle ? `<p>${esc(subtitle)}</p>` : ''}</div><button class="modal-close" data-close aria-label="Close">${icon('close')}</button></header><div class="modal-body">${body}</div></section></div>`;
  const close = () => { closeModal(); onClose?.(); };
  root.querySelector('[data-close]').addEventListener('click', close);
  root.querySelector('[data-backdrop]').addEventListener('click', e => { if (e.target === e.currentTarget) close(); });
  root.querySelectorAll('[data-cancel]').forEach(b => b.addEventListener('click', close));
  root.querySelector('.modal').addEventListener('keydown', e => {
    if (e.key === 'Escape') close();
    if (e.key === 'Tab') trapFocus(e, root.querySelector('.modal'));
  });
  (root.querySelector('.modal-body input, .modal-body select, .modal-body textarea, .modal-body button') || root.querySelector('[data-close]'))?.focus();
  return root.querySelector('.modal');
}
function trapFocus(e, container) {
  const items = [...container.querySelectorAll('a[href], button:not([disabled]), input:not([disabled]), select, textarea')].filter(el => el.offsetParent !== null);
  if (!items.length) return;
  const first = items[0], last = items[items.length - 1];
  if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
  else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
}
export function closeModal() {
  document.getElementById('overlay-root').innerHTML = '';
  if (lastFocus && document.contains(lastFocus)) lastFocus.focus();
}

// Disable a submit button while an async action runs; prevents double submits.
export async function busy(button, fn, label = 'Working…') {
  if (!button) return fn();
  if (button.disabled) return;
  const html = button.innerHTML;
  button.disabled = true; button.textContent = label;
  try { return await fn(); } finally { if (document.contains(button)) { button.disabled = false; button.innerHTML = html; } }
}

